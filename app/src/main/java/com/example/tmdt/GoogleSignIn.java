package com.example.tmdt;

import android.app.Activity;
import android.content.Context;
import android.content.MutableContextWrapper;
import android.os.CancellationSignal;
import androidx.core.content.ContextCompat;
import androidx.credentials.ClearCredentialStateRequest;
import androidx.credentials.CredentialManager;
import androidx.credentials.CredentialManagerCallback;
import androidx.credentials.CustomCredential;
import androidx.credentials.GetCredentialRequest;
import androidx.credentials.GetCredentialResponse;
import androidx.credentials.exceptions.ClearCredentialException;
import androidx.credentials.exceptions.GetCredentialCancellationException;
import androidx.credentials.exceptions.GetCredentialException;
import androidx.credentials.exceptions.GetCredentialProviderConfigurationException;
import androidx.credentials.exceptions.GetCredentialUnsupportedException;
import androidx.credentials.exceptions.NoCredentialException;
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption;
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential;

/** Credential selection only. Firebase verifies the returned token in AccountState. */
public final class GoogleSignIn {
    private GoogleSignIn() {}
    public interface Callback {
        void token(String token);
        void stopped(String error);
    }

    public static String clientId(Context context) {
        // Generated by google-services only when the downloaded JSON contains a web OAuth client.
        int id=context.getResources().getIdentifier("default_web_client_id","string",context.getPackageName());
        return id==0?"":context.getString(id).trim();
    }

    public static void launch(Activity activity, CancellationSignal cancellation, Callback callback) {
        Context app=activity.getApplicationContext();
        MutableContextWrapper context=new MutableContextWrapper(activity);
        GetCredentialRequest request=new GetCredentialRequest.Builder()
                .addCredentialOption(new GetSignInWithGoogleOption.Builder(clientId(app)).build()).build();
        cancellation.setOnCancelListener(()->context.setBaseContext(app));
        try {
            CredentialManager.create(app).getCredentialAsync(context,request,cancellation,
                    ContextCompat.getMainExecutor(app),new CredentialManagerCallback<GetCredentialResponse,GetCredentialException>() {
                        @Override public void onResult(GetCredentialResponse result) {
                            context.setBaseContext(app);
                            if(cancellation.isCanceled())return;
                            if(result.getCredential() instanceof CustomCredential &&
                                    GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL.equals(result.getCredential().getType())) {
                                try {
                                    callback.token(GoogleIdTokenCredential.createFrom(result.getCredential().getData()).getIdToken());
                                } catch(Exception e) {callback.stopped(app.getString(R.string.google_invalid_response));}
                            } else callback.stopped(app.getString(R.string.google_invalid_response));
                        }
                        @Override public void onError(GetCredentialException error) {
                            context.setBaseContext(app);
                            if(cancellation.isCanceled())return;
                            if(error instanceof GetCredentialCancellationException)callback.stopped("");
                            else if(error instanceof NoCredentialException)callback.stopped(app.getString(R.string.google_no_account));
                            else if(error instanceof GetCredentialProviderConfigurationException || error instanceof GetCredentialUnsupportedException)
                                callback.stopped(app.getString(R.string.google_services_unavailable));
                            else callback.stopped(app.getString(R.string.google_sign_in_failed));
                        }
                    });
        } catch(RuntimeException e) {
            context.setBaseContext(app);
            callback.stopped(app.getString(R.string.google_sign_in_failed));
        }
    }

    public static void clearSession(Context context) {
        try {
            CredentialManager.create(context).clearCredentialStateAsync(new ClearCredentialStateRequest(),null,
                ContextCompat.getMainExecutor(context),new CredentialManagerCallback<Void,ClearCredentialException>() {
                    @Override public void onResult(Void result) {}
                    // Firebase sign-out remains effective when a device has no credential provider.
                    @Override public void onError(ClearCredentialException error) {}
                });
        } catch(RuntimeException unavailableProvider) {
            // Clearing optional Google state must never prevent Firebase sign-out.
        }
    }
}
